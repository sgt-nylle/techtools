#!/usr/bin/env node
/**
 * Generates src/tools/geo/worldLand.ts — a single equirectangular SVG path (viewBox 0 0 1000 500)
 * of the world's land masses, from Natural Earth 1:110m land (public domain) via the world-atlas TopoJSON.
 *
 * Runs at development time only; the generated path is committed so the app ships a fully self-hosted
 * map with zero runtime tile / CDN requests (strict CSP stays intact).
 *
 *   node scripts/build-world-map.mjs            (or: npm run map:build)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC = process.env.WORLD_ATLAS_URL || 'https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json';
const OUT = path.resolve(__dirname, '../src/tools/geo/worldLand.ts');
const W = 1000;
const H = 500;

const res = await fetch(SRC);
if (!res.ok) throw new Error(`Download failed: ${res.status} ${SRC}`);
const topo = await res.json();

const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;

// Decode delta-encoded, quantized arcs into absolute [lon, lat] coordinates.
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});

const arcPoints = (i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ringPoints = (arcIdxs) => {
  const pts = [];
  arcIdxs.forEach((i, k) => {
    const a = arcPoints(i);
    pts.push(...(k === 0 ? a : a.slice(1)));
  });
  return pts;
};

const project = ([lon, lat]) => [((lon + 180) * W) / 360, ((90 - lat) * H) / 180];
const fmt = (n) => String(Math.round(n * 10) / 10);

const land = topo.objects.land;
const geometries = land.type === 'GeometryCollection' ? land.geometries : [land];
const polygons = [];
for (const g of geometries) {
  if (g.type === 'Polygon') polygons.push(g.arcs);
  else if (g.type === 'MultiPolygon') polygons.push(...g.arcs);
}

let d = '';
let points = 0;

/** Emit one projected ring as an SVG subpath (dropping duplicate rounded vertices). */
const emitRing = (lonLatPts, lonShift = 0) => {
  let prev = '';
  let seg = '';
  for (const [lon, lat] of lonLatPts) {
    const [x, y] = project([lon + lonShift, lat]);
    const key = `${fmt(x)},${fmt(y)}`;
    if (key === prev) continue;
    seg += seg ? ` ${key}` : `M${key}`;
    prev = key;
    points += 1;
  }
  if (seg) d += `${seg}Z`;
};

for (const poly of polygons) {
  for (const ring of poly) {
    const raw = ringPoints(ring);
    // Unwrap longitudes across the antimeridian so rings crossing ±180° (Chukotka, Fiji, ...) stay contiguous
    // instead of drawing a horizontal line across the whole map. Off-map parts are mirrored by ±360°.
    const unwrapped = [];
    let offset = 0;
    raw.forEach(([lon, lat], i) => {
      if (i > 0) {
        const prevLon = raw[i - 1][0];
        if (lon - prevLon > 180) offset -= 360;
        else if (prevLon - lon > 180) offset += 360;
      }
      unwrapped.push([lon + offset, lat]);
    });
    if (offset !== 0) {
      // Net winding around the globe (pole-enclosing ring, e.g. Antarctica): the source ring already runs
      // along the ±180° map edges, so the original coordinates render correctly.
      emitRing(raw);
      continue;
    }
    emitRing(unwrapped);
    const lons = unwrapped.map((p) => p[0]);
    if (Math.max(...lons) > 180) emitRing(unwrapped, -360);
    if (Math.min(...lons) < -180) emitRing(unwrapped, 360);
  }
}

const out = `/**
 * AUTO-GENERATED by scripts/build-world-map.mjs — do not edit by hand.
 * Natural Earth 1:110m land (public domain, https://www.naturalearthdata.com) via world-atlas TopoJSON,
 * projected equirectangular onto viewBox "0 0 ${W} ${H}": x = (lon + 180) * (${W} / 360), y = (90 - lat) * (${H} / 180).
 * ${polygons.length} polygons • ${points} vertices.
 */
export const WORLD_MAP_WIDTH = ${W};
export const WORLD_MAP_HEIGHT = ${H};
export const WORLD_LAND_PATH =
  '${d}';
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${polygons.length} polygons, ${points} vertices, ${(out.length / 1024).toFixed(1)} KiB)`);
